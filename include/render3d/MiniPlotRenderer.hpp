#pragma once

#include "analysis/PerFrameDistributionStore.hpp"
#include "math/Precision.hpp"

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <vector>

namespace correlation::render3d {

/**
 * @brief Standard 32-bit RGBA pixel representation.
 */
struct RgbaPixel {
  uint8_t r{0};   ///< Red channel (0-255)
  uint8_t g{0};   ///< Green channel (0-255)
  uint8_t b{0};   ///< Blue channel (0-255)
  uint8_t a{255}; ///< Alpha channel (0-255)
};

/**
 * @brief Raw RGBA pixel buffer generated by MiniPlotRenderer.
 */
struct PlotImageBuffer {
  uint32_t width{0};            ///< Buffer width in pixels
  uint32_t height{0};           ///< Buffer height in pixels
  std::vector<RgbaPixel> pixels; ///< Pixel array (size = width * height)
};

/**
 * @brief Detected peak position on a 1D distribution profile.
 */
struct PeakInfo {
  real_t x{0.0};     ///< X-axis coordinate of peak
  real_t y{0.0};     ///< Amplitude of peak
  bool valid{false}; ///< True if a valid local maximum was found
};

/**
 * @brief High-performance 2D software renderer for distribution mini-charts.
 *
 * Employs zero-allocation drawing routines to produce anti-aliased distribution curves,
 * overlays of current-frame vs ensemble mean, and peak markers in sub-millisecond execution.
 */
class MiniPlotRenderer {
public:
  static constexpr uint32_t kDefaultWidth = 260;
  static constexpr uint32_t kDefaultHeight = 130;

  /**
   * @brief Renders a 2D mini distribution plot into an RGBA pixel buffer.
   * @param[in] metric_data Metric dataset containing bins, mean curve, and per-frame curves.
   * @param[in] frame_idx Optional frame index to render on top of the mean.
   * @param[in] width Target canvas width in pixels.
   * @param[in] height Target canvas height in pixels.
   * @return Generated PlotImageBuffer suitable for conversion to slint::SharedPixelBuffer.
   */
  [[nodiscard]] static PlotImageBuffer
  render(const analysis::MetricCurveData &metric_data,
         std::optional<std::size_t> frame_idx = std::nullopt,
         uint32_t width = kDefaultWidth,
         uint32_t height = kDefaultHeight);

  /**
   * @brief Finds the primary local maximum peak in a 1D curve.
   * @param[in] bins X coordinates.
   * @param[in] values Y coordinates.
   * @return Detected PeakInfo.
   */
  [[nodiscard]] static PeakInfo findPeak(std::span<const real_t> bins,
                                        std::span<const real_t> values) noexcept;
};

} // namespace correlation::render3d

