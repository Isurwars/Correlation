#include "writers/structure/CifWriter.hpp"
#include "writers/structure/StructureWriterFactory.hpp"

#include <cmath>
#include <fstream>
#include <iomanip>
#include <map>
#include <stdexcept>
#include <string>

namespace correlation::writers::structure {

// Static self-registration in factory
const bool CIF_REGISTERED = StructureWriterFactory::registerTypeSafe<CifWriter>("CifWriter");

namespace {

void validateCell(const correlation::core::Cell &cell, const std::string &filepath) {
  if (cell.volume() <= 1e-9) {
    throw std::runtime_error("Cannot write CIF to '" + filepath +
                             "': cell volume is degenerate or non-periodic.");
  }
  if (cell.atoms().empty()) {
    throw std::runtime_error("Cannot write CIF to '" + filepath + "': cell contains no atoms.");
  }
}

void writeCellParameters(std::ostream &out, const correlation::core::Cell &cell) {
  const auto &params = cell.latticeParameters();
  out << std::fixed << std::setprecision(6);
  out << "_cell_length_a                   " << params[0] << "\n";
  out << "_cell_length_b                   " << params[1] << "\n";
  out << "_cell_length_c                   " << params[2] << "\n";
  out << "_cell_angle_alpha                " << params[3] << "\n";
  out << "_cell_angle_beta                 " << params[4] << "\n";
  out << "_cell_angle_gamma                " << params[5] << "\n";
  out << "_cell_volume                     " << cell.volume() << "\n\n";
}

void writeSymmetryBlock(std::ostream &out) {
  out << "_symmetry_space_group_name_H-M   'P 1'\n";
  out << "_symmetry_Int_Tables_number      1\n\n";
  out << "loop_\n";
  out << "  _symmetry_equiv_pos_as_xyz\n";
  out << "  'x, y, z'\n\n";
}

void writeAtomSitesLoop(std::ostream &out, const correlation::core::Cell &cell) {
  out << "loop_\n";
  out << "  _atom_site_label\n";
  out << "  _atom_site_type_symbol\n";
  out << "  _atom_site_fract_x\n";
  out << "  _atom_site_fract_y\n";
  out << "  _atom_site_fract_z\n";
  out << "  _atom_site_occupancy\n";

  const auto &inv_lattice = cell.inverseLatticeVectors();
  std::map<std::string, std::size_t> element_counts;

  out << std::fixed << std::setprecision(8);
  for (std::size_t idx = 0; idx < cell.atoms().size(); ++idx) {
    const auto &atom = cell.atoms()[idx];
    const std::string &sym = atom.element().symbol;
    if (sym.empty()) {
      throw std::runtime_error("Cannot write CIF: atom index " + std::to_string(idx) +
                               " has an empty chemical symbol.");
    }

    element_counts[sym]++;
    std::string const label = sym + std::to_string(element_counts[sym]);

    correlation::math::Vector3<real_t> coords = inv_lattice * atom.position();
    for (std::size_t dim = 0; dim < 3; ++dim) {
      real_t val = coords[dim] - std::floor(coords[dim]);
      if (std::abs(val - 1.0) < 1e-12) {
        val = 0.0;
      }
      coords[dim] = val;
    }

    out << "  " << std::left << std::setw(8) << label << " " << std::setw(4) << sym << " "
        << std::right << std::setw(14) << coords[0] << " " << std::setw(14) << coords[1] << " "
        << std::setw(14) << coords[2] << "  1.0000\n";
  }
}

} // namespace

void CifWriter::write(const std::string &filepath, const correlation::core::Cell &cell,
                      const StructureWriterOptions &options) const {
  validateCell(cell, filepath);

  std::ofstream out(filepath);
  if (!out.is_open()) {
    throw std::runtime_error("Unable to open destination file for writing: " + filepath);
  }

  out << "# CIF file generated by Correlation\n";
  if (!options.title.empty()) {
    out << "# " << options.title << "\n";
  }
  out << "data_correlation_cell\n";
  out << "_audit_creation_method           'Correlation'\n\n";

  writeCellParameters(out, cell);
  writeSymmetryBlock(out);
  writeAtomSitesLoop(out, cell);
}

} // namespace correlation::writers::structure
