#include "writers/structure/CellWriter.hpp"
#include "writers/structure/StructureWriterFactory.hpp"

#include <cmath>
#include <fstream>
#include <iomanip>
#include <stdexcept>
#include <string>

namespace correlation::writers::structure {

// Static self-registration in factory
const bool CELL_REGISTERED = StructureWriterFactory::registerTypeSafe<CellWriter>("CellWriter");

namespace {

void validateCell(const correlation::core::Cell &cell, const std::string &filepath) {
  if (cell.volume() <= 1e-9) {
    throw std::runtime_error("Cannot write CASTEP .cell to '" + filepath +
                             "': cell volume is degenerate or non-periodic.");
  }
  if (cell.atoms().empty()) {
    throw std::runtime_error("Cannot write CASTEP .cell to '" + filepath +
                             "': cell contains no atoms.");
  }
}

void writeLatticeBlock(std::ostream &out, const correlation::core::Cell &cell) {
  out << "%BLOCK LATTICE_CART\n";
  out << std::fixed << std::setprecision(10);
  const auto &lattice = cell.latticeVectors();
  for (std::size_t i = 0; i < 3; ++i) {
    out << "  " << std::setw(16) << lattice[i][0] << " " << std::setw(16) << lattice[i][1] << " "
        << std::setw(16) << lattice[i][2] << "\n";
  }
  out << "%ENDBLOCK LATTICE_CART\n\n";
}

void writePositionsBlock(std::ostream &out, const correlation::core::Cell &cell, bool fractional) {
  if (fractional) {
    out << "%BLOCK POSITIONS_FRAC\n";
  } else {
    out << "%BLOCK POSITIONS_ABS\n";
  }

  const auto &inv_lattice = cell.inverseLatticeVectors();
  out << std::fixed << std::setprecision(10);

  for (std::size_t idx = 0; idx < cell.atoms().size(); ++idx) {
    const auto &atom = cell.atoms()[idx];
    const std::string &sym = atom.element().symbol;
    if (sym.empty()) {
      throw std::runtime_error("Cannot write CASTEP .cell: atom index " + std::to_string(idx) +
                               " has an empty chemical symbol.");
    }

    correlation::math::Vector3<real_t> coords;
    if (fractional) {
      coords = inv_lattice * atom.position();
      for (std::size_t dim = 0; dim < 3; ++dim) {
        real_t val = coords[dim] - std::floor(coords[dim]);
        if (std::abs(val - 1.0) < 1e-12) {
          val = 0.0;
        }
        coords[dim] = val;
      }
    } else {
      coords = atom.position();
    }

    out << "  " << std::left << std::setw(4) << sym << "  " << std::right << std::setw(16)
        << coords[0] << " " << std::setw(16) << coords[1] << " " << std::setw(16) << coords[2]
        << "\n";
  }

  if (fractional) {
    out << "%ENDBLOCK POSITIONS_FRAC\n";
  } else {
    out << "%ENDBLOCK POSITIONS_ABS\n";
  }
}

} // namespace

void CellWriter::write(const std::string &filepath, const correlation::core::Cell &cell,
                       const StructureWriterOptions &options) const {
  validateCell(cell, filepath);

  std::ofstream out(filepath);
  if (!out.is_open()) {
    throw std::runtime_error("Unable to open destination file for writing: " + filepath);
  }

  out << "# CASTEP .cell file generated by Correlation\n";
  if (!options.title.empty()) {
    out << "# " << options.title << "\n";
  }
  out << "\n";

  writeLatticeBlock(out, cell);
  writePositionsBlock(out, cell, options.fractional);
}

} // namespace correlation::writers::structure
