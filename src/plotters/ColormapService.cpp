RgbaColor ColormapService::sample(double value, ColormapType type) noexcept {
  const auto lut = getLut(type);
  if (std::isnan(value) || value <= 0.0) {
    return lut.front();
  }
  if (value >= 1.0) {
    return lut.back();
  }
  const auto idx = static_cast<size_t>(std::lround(value * 255.0));
  return lut[std::min(idx, size_t{255})];
}

std::span<const RgbaColor, 256> ColormapService::getLut(ColormapType type) noexcept {
  switch (type) {
  case ColormapType::Viridis:
    return VIRIDIS_LUT;
  case ColormapType::Plasma:
    return PLASMA_LUT;
  case ColormapType::Coolwarm:
    return COOLWARM_LUT;
  case ColormapType::Turbo:
    return TURBO_LUT;
  }
  return VIRIDIS_LUT;
}

std::string_view ColormapService::name(ColormapType type) noexcept {
  switch (type) {
  case ColormapType::Viridis:
    return "Viridis";
  case ColormapType::Plasma:
    return "Plasma";
  case ColormapType::Coolwarm:
    return "Coolwarm";
  case ColormapType::Turbo:
    return "Turbo";
  }
  return "Viridis";
}

std::optional<ColormapType> ColormapService::fromString(std::string_view name) noexcept {
  if (name.empty()) {
    return std::nullopt;
  }
  const auto iequals = [](std::string_view lhs, std::string_view rhs) noexcept {
    if (lhs.size() != rhs.size()) {
      return false;
    }
    for (size_t idx = 0; idx < lhs.size(); ++idx) {
      if (std::tolower(static_cast<unsigned char>(lhs[idx])) !=
          std::tolower(static_cast<unsigned char>(rhs[idx]))) {
        return false;
      }
    }
    return true;
  };

  if (iequals(name, "viridis")) {
    return ColormapType::Viridis;
  }
  if (iequals(name, "plasma")) {
    return ColormapType::Plasma;
  }
  if (iequals(name, "coolwarm")) {
    return ColormapType::Coolwarm;
  }
  if (iequals(name, "turbo")) {
    return ColormapType::Turbo;
  }
  return std::nullopt;
}

